// 2.19: notes with pictures or files show a small picture and icons in the list and grid.
import { chromium } from 'playwright';
import fs from 'node:fs';
const BASE = process.env.BASE || 'http://127.0.0.1:8787';
const OUT = process.env.SHOTS || 'test/shots';
const step = (s) => console.log('•', s);
const browser = await chromium.launch();
const errors = [];
const A = await (await browser.newContext({ viewport: { width: 1280, height: 860 } })).newPage();
A.on('pageerror', (e) => errors.push(e.message));
A.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errors.push(m.text()); });
await A.goto(BASE + '/');
await A.waitForSelector('.status-chip[data-state="online"]', { timeout: 15000 });
const png = fs.readFileSync(new URL('../public/icons/icon-512.png', import.meta.url));
await A.click('.tab[data-tab="notes"]');
await A.click('#btn-new-note');
await A.keyboard.type('Trip photos');
await A.keyboard.press('Enter');
await A.setInputFiles('#note-file-input', [{ name: 'a.png', mimeType: 'image/png', buffer: png }, { name: 'b.png', mimeType: 'image/png', buffer: png }, { name: 'list.txt', mimeType: 'text/plain', buffer: Buffer.from('x') }]);
await A.waitForFunction(() => document.querySelectorAll('#editor-text [data-file]').length === 3);
await A.click('#btn-new-canvas');
await A.setInputFiles('.cv-file', [{ name: 'c.png', mimeType: 'image/png', buffer: png }]);
await A.waitForSelector('.cv-obj.cv-img');
await A.click('#btn-new-note');
await A.keyboard.type('Plain text only');
await A.waitForTimeout(1200);
await A.click('#btn-editor-back');
const info = await A.$$eval('.note-item', (l) => l.map((b) => ({ t: b.querySelector('.t span').textContent, thumb: !!b.querySelector('.ni-thumb'), badges: [...b.querySelectorAll('.ni-badge')].map((x) => x.textContent || '1').join('+') })));
const trip = info.find((x) => x.t === 'Trip photos');
const canvas = info.find((x) => x.t !== 'Trip photos' && x.t !== 'Plain text only');
const plain = info.find((x) => x.t === 'Plain text only');
if (!trip || !trip.thumb || trip.badges !== '2+1') throw new Error('trip ' + JSON.stringify(info));
if (!canvas || !canvas.thumb) throw new Error('canvas ' + JSON.stringify(info));
if (!plain || plain.thumb || plain.badges) throw new Error('plain ' + JSON.stringify(info));
await A.waitForFunction(() => [...document.querySelectorAll('.ni-thumb')].every((i) => i.complete && i.naturalWidth > 0));
await A.screenshot({ path: `${OUT}/170-list-thumbs.png` });
await A.click('#btn-notes-view'); await A.click('.menu button:has-text("Grid")');
await A.screenshot({ path: `${OUT}/171-grid-thumbs.png` });
await A.click('#btn-notes-view'); await A.click('.menu button:has-text("List")');
step('List and grid: a small picture + picture/file icons (with counts); plain notes stay plain; canvases too');
if (errors.length) { console.log(errors); throw new Error('page errors'); }
await browser.close();
console.log('ALL OK');
